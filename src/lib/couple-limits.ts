/**
 * `couples`의 5개 예식 정보 필드에 대한 **입력 상한**. 온보딩과 설정 › 예식 정보가 같이 쓴다.
 *
 * `lib/membership.ts`와 같은 처방이다 — 이 값들은 화면 문구에 박히고("1조 원 미만으로"),
 * 그 문구 모듈을 클라이언트 컴포넌트가 import한다. 그래서 이 파일은 **아무것도 import하지 않는다.**
 * 서버·클라이언트 어디서든 안전하다. (같은 처방 → D-054, D-064)
 *
 * ─────────────────────────────────────────────────────────────────
 * 🔴 **여기 있는 값은 DB 제약의 사본이 아니다. 두 종류가 섞여 있다.**
 *
 * | 값 | 출처 |
 * |---|---|
 * | 하한 0 | **DB가 정했다** — 5개 컬럼 전부 `check (>= 0)` (0001) |
 * | 상한 | **우리가 골랐다** — DB는 bigint/int4 한계까지 받는다 |
 *
 * 상한을 DB 한계로 두지 않는 이유는 `MoneyText`가 375px에서 터지기 때문이다.
 * 예: 보증인원을 int4 최대(2,147,483,647)로 허용하면 부족분 식대가
 * `21억 × 70,000 ≈ 1.5×10^14`이 되어 하객 화면의 금액 칸이 무너진다.
 *
 * 그래서 상한을 바꿀 때 마이그레이션은 손댈 필요가 없다. 대신 **금액이 렌더되는 자리를
 * 실제로 확인해야 한다** — 이 숫자들이 지키는 것은 DB 무결성이 아니라 레이아웃이다.
 */

/**
 * 총 가용예산 상한(1조 미만). `couples.total_budget`이 bigint라 자릿수를 안 막으면
 * `Number`가 정밀도를 잃은 값이 그대로 들어간다. 조용히 잘라내지 않고 **되돌려 말한다**.
 */
export const MAX_TOTAL_BUDGET = 999_999_999_999;

/**
 * 최소보증인원 상한(1만 명).
 *
 * `couples.guest_min_guarantee`만 **int4**라 DB 자체 한계는 2,147,483,647이지만,
 * 그 값을 그대로 쓰면 `gap × meal_cost_per_head`가 금액 칸을 터뜨린다(위 주석).
 *
 * 1만은 국내 최대 예식장(1,000명대)의 열 배다. 넉넉히 잡되 **자릿수 오타를 잡는 선**이라
 * 이 값을 골랐다 — `2000`을 `20000`으로 잘못 치면 부족분 식대가 억 단위 헛경고가 되는데,
 * 그 화면(하객 탭)은 사람이 숫자를 믿고 계약을 다시 들여다보는 자리다.
 * **DB가 정한 숫자가 아니라 우리가 고른 숫자다.**
 */
export const MAX_GUEST_GUARANTEE = 10_000;

/**
 * **1인당** 금액(평균 축의금 · 1인 식대)의 상한(1억).
 *
 * 총액이 아니라 1인당이라 총예산과 자릿수가 다르다. 근거는 곱셈의 안전성이다 —
 * `예상 참석 인원 × 평균 축의금`이 `Number.MAX_SAFE_INTEGER`(약 9×10^15) 안에 머물러야 한다.
 * 10만 명 × 1억 = 10^13이라 안전하다. 여기에 `MAX_TOTAL_BUDGET`(1조)을 그대로 쓰면
 * 10만 × 1조 = 10^17로 **정밀도를 잃는다.**
 */
export const MAX_UNIT_AMOUNT = 100_000_000;

/**
 * 카테고리 이름 길이 상한(20자).
 *
 * 위 넷과 달리 `couples`가 아니라 `categories.name`에 대한 값이지만, 같은 성격이라 여기 모은다 —
 * **DB 제약의 사본이 아니라 우리가 고른 숫자다.** 0002는 `length(btrim(name)) > 0`만 걸고
 * 길이 상한은 두지 않는다.
 *
 * 20자를 고른 근거는 `ListRow`의 `truncate`다. 375px에서 소분류 행은 좌측 표식(36px) ·
 * 우측 ↑↓ 버튼 쌍 · 좌우 패딩을 빼면 이름에 남는 폭이 대략 20자다. 그보다 길면 잘려서
 * **목록에서 두 항목을 구분할 수 없게 된다** — 자르는 대신 입력 시점에 되돌려 말한다.
 * 시드 중 가장 긴 이름이 "신부 메이크업"(7자)이라 실사용과는 여유가 크다.
 */
export const MAX_CATEGORY_NAME_LENGTH = 20;
